//! 构建脚本。
//!
//! 目前只做标准 Tauri 构建。
//!
//! # 为什么这里没有「编译期注入激活码公钥」
//! ────────────────────────────────────────────────────────────
//! 曾计划在此注入 RSA 公钥（通过 `XUANDUN_LICENSE_PUBKEY` 环境变量
//! 注入为编译期常量），已放弃。原因是架构调整：
//! 验签搬到了 Python 引擎侧（见 `src/license.rs` 顶部注释），
//! 公钥随之由引擎在运行时从环境变量 / 磁盘读取，
//! Rust 侧不再需要它。
//!
//! 那 Rust 侧还需要什么？只有**机器码采集**，
//! 而机器码必须明文交给引擎去哈希（哈希算法在引擎侧，
//! 与签发工具对齐），所以不存在「Rust 侧藏公钥」的需求。
//!
//! 未来若要把某个密钥材料编译进二进制，应在此处注入 ——
//! 注入比写死在 .rs 源文件里好，因为后者等于给反编译者一份说明书。

fn main() {
    tauri_build::build()
}
