const EN: Record<string, string> = Object.fromEntries(EN_PAIRS);

let currentLang: Lang = 'zh';

/** 读取系统语言偏好。 */
function systemLang(): Lang {
  if (typeof navigator === 'undefined') return 'zh';
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

/** 首次启动：localStorage 优先，其次跟随系统。 */
export function detectLang(): Lang {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  }
  return systemLang();
}

export function getLang(): Lang {
  return currentLang;
}

/** 非组件模块用：按当前语言翻译。 */
export function t(zh: string): string {
  return currentLang === 'en' ? (EN[zh] ?? zh) : zh;
}

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (zh: string) => string;
}

const LangContext = createContext<I18nValue>({
  lang: 'zh',
  setLang: () => undefined,
  t: (zh) => zh,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => detectLang());

  // 初始化时把模块级语言同步好，保证非组件代码（如 api.ts）也拿到正确语言。
  useEffect(() => {
    currentLang = lang;
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    // ★ 2026-11-09：托盘菜单在 Rust 侧构建，必须显式同步语言，
    //   否则英文界面下右键托盘仍是中文。浏览器预览没有该命令，忽略即可。
    void (async () => {
      try {
        const { isTauri, invoke } = await import('../lib/tauriShim');
        if (isTauri()) await invoke('set_tray_lang', { lang });
      } catch {
        // 旧版本桌面端尚未注册该命令，保持默认中文
      }
    })();
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    currentLang = next;
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // 隐私模式下 localStorage 可能不可写；语言仍在本会话生效。
    }
    setLangState(next);
  }, []);

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      t: (zh: string) => (lang === 'en' ? (EN[zh] ?? zh) : zh),
    }),
    [lang, setLang],
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(LangContext);
}
